#!/usr/bin/env node
/* ==========================================================================
   AIMLAB WEB · build.mjs
   把 src/index.html + 2 个 CSS + JS 模块 + 素材（音效/绿幕视频/表情包）
   内联成一个可双击打开的 HTML。
   用法：
     node work/build.mjs            # 完整构建（含素材，供交付）
     node work/build.mjs --no-assets# 快速构建（不内联素材，仅供本地 HTTP 调试）
   ========================================================================== */
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SRC = join(__dirname, 'src');
const ASSETS = join(SRC, 'assets');
const OUT_DIR = join(__dirname, 'dist');
const OUT_FILE = join(OUT_DIR, 'index.html');
const NO_ASSETS = process.argv.includes('--no-assets');
const EXPECTED_SCRIPTS = ['js/store.js', 'js/crosshair.js', 'js/meme-extra.js', 'js/meme.js', 'js/game.js', 'js/ui.js', 'js/main.js'];

function fail(message) {
  console.error('\n[build] ✗ ' + message + '\n');
  process.exit(1);
}

function read(rel) {
  const file = join(SRC, rel);
  if (!existsSync(file)) fail('缺少源文件: ' + file);
  return readFileSync(file, 'utf8');
}

function walkFiles(dir, out) {
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) walkFiles(full, out);
    else if (stat.isFile()) out.push(full);
  }
  return out;
}

function mimeFor(file) {
  const ext = extname(file).toLowerCase();
  const map = {
    '.mp3': 'audio/mpeg',
    '.wav': 'audio/wav',
    '.ogg': 'audio/ogg',
    '.mp4': 'video/mp4',
    '.webm': 'video/webm',
    '.svg': 'image/svg+xml',
    '.png': 'image/png',
    '.jpg': 'image/jpeg',
    '.jpeg': 'image/jpeg',
    '.gif': 'image/gif',
    '.webp': 'image/webp',
  };
  return map[ext] || 'application/octet-stream';
}

/* ── 1. HTML 与 CSS / JS ─────────────────────────────────────────────── */
let html = read('index.html');

html = html.replace(/<link rel="stylesheet" href="([^"]+)" data-build="inline">/g, (_match, rel) => {
  const css = read(rel);
  if (/<\/style/i.test(css)) fail(rel + ' 中包含 </style>，无法安全内联');
  if (/@import\s+url\(/i.test(css)) fail(rel + ' 不允许 @import 外链资源');
  return '<!-- build:' + rel + ' -->\n  <style>\n' + css + '\n  </style>';
});

let scriptCount = 0;
const inlinedScripts = [];
html = html.replace(/<script src="([^"]+)" data-build="inline"><\/script>/g, (_match, rel) => {
  const js = read(rel);
  if (/<\/script/i.test(js)) fail(rel + ' 中包含 </script>，无法安全内联');
  scriptCount += 1;
  inlinedScripts.push(rel);
  return '<!-- build:' + rel + ' -->\n  <script>\n' + js + '\n  </script>';
});
if (scriptCount !== EXPECTED_SCRIPTS.length) {
  fail('内联脚本数量不对：期望 ' + EXPECTED_SCRIPTS.length + '，实际 ' + scriptCount + '（' + inlinedScripts.join(', ') + '）');
}

/* ── 2. 素材内联 ─────────────────────────────────────────────────────── */
let assetCount = 0;
let assetBytes = 0;
let assetScript = '';
if (NO_ASSETS) {
  assetScript = '<!-- build: assets skipped (--no-assets) -->';
} else {
  const files = walkFiles(ASSETS, []).sort();
  if (!files.length) fail('src/assets 目录不存在或没有素材');
  const data = {};
  for (const file of files) {
    const rel = relative(ASSETS, file).split(sep).join('/');
    const bytes = readFileSync(file);
    assetBytes += bytes.length;
    assetCount += 1;
    data[rel] = 'data:' + mimeFor(file) + ';base64,' + bytes.toString('base64');
  }
  const json = JSON.stringify(data);
  if (/<\/script/i.test(json)) fail('素材 data URI 中出现 </script>，无法安全内联');
  assetScript =
    '<!-- build: memefx assets · ' + assetCount + ' files · ' + (assetBytes / 1024 / 1024).toFixed(2) + ' MB -->\n' +
    '  <script>window.__MEME_ASSETS__ = ' + json + ';</script>';
}
if (!html.includes('<script data-build="assets"></script>')) fail('index.html 中找不到素材占位脚本');
html = html.replace('<script data-build="assets"></script>', assetScript);

const externalScripts = html.match(/<script\s+src=|<link[^>]+stylesheet/i);
if (externalScripts) fail('构建结果中仍有未内联的外部资源引用');

/* ── 3. 输出 ─────────────────────────────────────────────────────────── */
const banner =
  '<!-- AIMLAB WEB · single-file build · ' +
  new Date().toISOString() +
  (NO_ASSETS ? ' · NO ASSETS (debug)' : ' · assets inlined') +
  ' · generated by work/build.mjs -->\n';
html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + banner);

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT_FILE, html, 'utf8');

const totalKB = statSync(OUT_FILE).size / 1024;
console.log('[build] ✓ ' + OUT_FILE);
console.log(
  '[build]   ' +
    totalKB.toFixed(1) +
    ' KB total · ' +
    scriptCount +
    ' scripts · ' +
    (NO_ASSETS ? 'assets skipped' : assetCount + ' assets / ' + (assetBytes / 1024 / 1024).toFixed(2) + ' MB inlined')
);
if (totalKB > 16 * 1024) console.warn('[build] ⚠ 产物超过 16MB，建议压缩视频/收窄素材池。');
